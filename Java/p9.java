class p9 
{
	public static void main(String[] args) 
	{
		int a = 10;
		System.out.println(a);
		a += 5; /* a=a+5 */
		System.out.println(a);
		a -= 3; /* a=a-3 */
		System.out.println(a);
		a *= 5; /* a=a*5 */
		System.out.println(a);
		a /= 7; /* a=a/5 */
		System.out.println(a);
		a %= 5; /* a=a%5 */
		System.out.println(a);
	}
}
